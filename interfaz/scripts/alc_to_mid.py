"""Convert an Ableton Live MIDI clip (.alc) into a Standard MIDI File the highway can read.

Usage:
  python3 scripts/alc_to_mid.py CLIP.alc OUT.mid [--bpm 112] [--bars 8]
  python3 scripts/alc_to_mid.py CLIP.alc OUT.ts  [--bpm 112]     # TypeScript pattern for demoSong.ts

.alc files are gzipped Live-set XML. Notes live in <KeyTrack> elements as
<MidiNoteEvent Time=… Duration=…> (in beats) with the key in <MidiKey>. Only the clip's loop
region is exported; disabled notes are skipped. The output is a type-0 SMF on channel 10
(General MIDI drums), PPQ 480, with tempo + time signature, so it goes through the same
parser / lane mapper as any transcribed drums.mid. Pure stdlib: no mido needed.
"""

import argparse
import gzip
import json
import re
import struct
import sys
import xml.etree.ElementTree as ET

PPQ = 480
# Keys the highway maps to a lane (see drumLaneOf in src/utils/midiToFretboard.ts).
LANE_KEYS = {35, 36, *range(37, 41), 42, 44, 46, 47, 48, 50, 41, 43, 45, 49, 51, 52, 53, 55, 57, 59}


def read_clip(path):
    root = ET.fromstring(gzip.open(path).read())
    clip = root.find('.//MidiClip')
    if clip is None:
        sys.exit(f'{path}: no MIDI clip inside')
    loop = clip.find('Loop')
    start = float(loop.find('LoopStart').get('Value'))
    end = float(loop.find('LoopEnd').get('Value'))
    ts = clip.find('.//RemoteableTimeSignature')
    sig = (int(ts.find('Numerator').get('Value')), int(ts.find('Denominator').get('Value'))) if ts is not None else (4, 4)
    notes = []
    for kt in clip.iter('KeyTrack'):
        key = int(kt.find('MidiKey').get('Value'))
        for ev in kt.iter('MidiNoteEvent'):
            if ev.get('IsEnabled', 'true') == 'false':
                continue
            t = float(ev.get('Time'))
            if not start <= t < end:
                continue
            notes.append((t - start, key, float(ev.get('Duration')), max(1, min(127, round(float(ev.get('Velocity')))))))
    notes.sort()
    return notes, end - start, sig


def vlq(n):
    out = [n & 0x7F]
    while n > 0x7F:
        n >>= 7
        out.append(0x80 | (n & 0x7F))
    return bytes(reversed(out))


def write_mid(path, notes, length, sig, bpm, repeats, name):
    events = []  # (tick, order, bytes): note-offs sort before note-ons at the same tick
    for r in range(repeats):
        for t, key, dur, vel in notes:
            on = round((t + r * length) * PPQ)
            off = on + max(1, round(min(dur, 0.5) * PPQ))
            events.append((on, 1, bytes([0x99, key, vel])))
            events.append((off, 0, bytes([0x89, key, 0])))
    events.sort(key=lambda e: (e[0], e[1]))
    denom_pow = {1: 0, 2: 1, 4: 2, 8: 3, 16: 4}[sig[1]]
    track = bytearray()
    track += b'\x00\xff\x03' + vlq(len(name.encode())) + name.encode()
    track += b'\x00\xff\x51\x03' + struct.pack('>I', round(60_000_000 / bpm))[1:]
    track += b'\x00\xff\x58\x04' + bytes([sig[0], denom_pow, 24, 8])
    last = 0
    for tick, _, data in events:
        track += vlq(tick - last) + data
        last = tick
    track += b'\x00\xff\x2f\x00'
    with open(path, 'wb') as f:
        f.write(b'MThd' + struct.pack('>IHHH', 6, 0, 1, PPQ))
        f.write(b'MTrk' + struct.pack('>I', len(track)) + track)


def write_ts(path, notes, length, sig, name):
    rows = ',\n'.join(f'    [{round(t, 4)}, {k}, {round(min(d, 0.5), 4)}, {round(v / 127, 3)}]' for t, k, d, v in notes)
    with open(path, 'w') as f:
        f.write(
            f'// Generated by scripts/alc_to_mid.py from the Ableton Live clip "{name}". Do not edit by hand.\n'
            f'// Each note: [beat, GM drum key, length in beats, velocity 0-1].\n\n'
            f'export const DRUM_LOOP = {{\n  name: {json.dumps(name)},\n  beats: {length:g},\n'
            f'  timeSignature: [{sig[0]}, {sig[1]}] as [number, number],\n'
            f'  notes: [\n{rows},\n  ] as [number, number, number, number][],\n}}\n'
        )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('clip')
    ap.add_argument('out')
    ap.add_argument('--bpm', type=float, help='default: the "NNN bpm" in the clip name, else 120')
    ap.add_argument('--bars', type=int, help='repeat the loop to fill this many bars (.mid only)')
    a = ap.parse_args()

    name = re.sub(r'\.alc$', '', a.clip.rsplit('/', 1)[-1]).strip()
    m = re.search(r'(\d+(?:\.\d+)?)\s*bpm', name, re.I)
    bpm = a.bpm or (float(m.group(1)) if m else 120.0)
    notes, length, sig = read_clip(a.clip)
    if not notes:
        sys.exit(f'{a.clip}: clip has no notes in its loop region')

    unmapped = sorted({k for _, k, _, _ in notes if k not in LANE_KEYS})
    bar_beats = sig[0] * 4 / sig[1]
    print(f'{name}: {len(notes)} notes, {length:g} beats ({length / bar_beats:g} bars of {sig[0]}/{sig[1]}), {bpm:g} BPM')
    if unmapped:
        print(f'  warning: keys {unmapped} have no highway lane and will be dropped')

    if a.out.endswith('.ts'):
        write_ts(a.out, notes, length, sig, name)
    else:
        repeats = max(1, -(-round(a.bars * bar_beats) // round(length))) if a.bars else 1
        write_mid(a.out, notes, length, sig, bpm, repeats, name)
    print(f'  → {a.out}')


if __name__ == '__main__':
    main()
